import re
FIX={'تحسّ ن':'تحسّن','بعضً ا':'بعضاً','بالكِ بر':'بالكِبر','أُعامَ ل':'أُعامَل','مرّعلي':'مرّ علي','أمرّعليه':'أمرّ عليه'}
def clean(t):
    for a,b in FIX.items(): t=t.replace(a,b)
    t=re.sub(r'(أيّ)(?!ام)(?=[ء-ي])',r'\1 ',t)
    t=re.sub(r'(فيّ|عليّ|والديّ|السرّ|نبيّ)(?=[ء-ي])',r'\1 ',t)
    t=re.sub(r'\s+([،؟.:!»])',r'\1',t)
    t=t.replace('( ','(').replace(' )',')')
    return re.sub(r'\s+',' ',t).strip()
